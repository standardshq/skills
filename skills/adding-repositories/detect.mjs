#!/usr/bin/env node
/**
 * Proposes every field of a `repositories` record, each with where it came from.
 *
 *   node detect.mjs --checkout <dir> --github <dir> [--registered <file>] [--format table]
 *
 * `--checkout` is a fresh clone of the repository. `--github` is a folder of
 * JSON the agent fetched with its GitHub tools (`adding-repositories` § 2):
 * `repo.json`, `branches.json`, `rules.json` (the rulesets that apply to the
 * default branch), `protection.json` (its classic branch protection; absent
 * or a 404 body when there is none), `pulls.json` (recent merged pull
 * requests). Required checks are the union of both. `--registered`
 * is `[{ "fullName", "packages": ["<package name>"] }]` for the repositories
 * already in the workspace, to propose `consumes`.
 *
 * The script reads files and runs git on the checkout; it never calls GitHub
 * or the workspace. It prints `{ fields: { <name>: { value, source } }, gate }`
 * as JSON (or a table). Exit 0 when the repository has a gate (required
 * checks or verify commands); 1 when it has neither and must not be saved;
 * 2 on a usage or input error.
 */
import { execFile } from "node:child_process";
import { readFile, readdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);

/** Scripts that prove a change, in the order a gate should run them. */
const VERIFY_SCRIPTS = ["typecheck", "lint", "check", "test", "build"];
/** Scripts that restore seeded data. */
const RESET_SCRIPTS = ["db:reset", "reset", "seed", "db:seed"];
/** Workflow steps that prepare or tear down rather than prove. */
const SETUP_STEP = /\b(install|setup|down|create|resolve|sync|deploy|publish|upload)\b/;
/** Header markers of a file that is never edited by hand. */
const GENERATED_MARKERS = ["@generated", "DO NOT EDIT", "Code generated by", "auto-generated"];

async function readJson(path, fallback) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return fallback;
    throw new Error(`${path}: ${error.message}`);
  }
}

async function readText(path) {
  try {
    return await readFile(path, "utf8");
  } catch {
    return null;
  }
}

async function git(checkout, args) {
  try {
    const { stdout } = await run("git", ["-C", checkout, ...args], { maxBuffer: 64 * 1024 * 1024 });
    return stdout.trim();
  } catch {
    return "";
  }
}

const field = (value, source) => ({ value, source });

function packageManager(files) {
  if (files.has("pnpm-lock.yaml")) return "pnpm";
  if (files.has("yarn.lock")) return "yarn";
  if (files.has("bun.lockb") || files.has("bun.lock")) return "bun";
  return "npm";
}

/**
 * Single-line `run:` steps of the workflow jobs a pull request triggers.
 * Multi-line `run: |` and `run: >` blocks are skipped: the skill re-reads them.
 */
async function workflowRuns(checkout) {
  const dir = join(checkout, ".github", "workflows");
  let names = [];
  try {
    names = (await readdir(dir)).filter((name) => /\.ya?ml$/.test(name));
  } catch {
    return { pullRequest: [], deploy: [], skippedBlocks: [] };
  }
  const pullRequest = [];
  const deploy = [];
  const skippedBlocks = [];
  for (const name of names) {
    const text = (await readText(join(dir, name))) ?? "";
    const commands = [...text.matchAll(/^\s*(?:-\s*)?run:\s*([^|>\n][^\n]*)$/gm)].map((match) =>
      match[1].trim(),
    );
    if (/\bpull_request\b|\bmerge_group\b/.test(text)) {
      for (const command of commands) pullRequest.push({ command, file: name });
      if (/^\s*(?:-\s*)?run:\s*[|>]/m.test(text)) skippedBlocks.push(name);
    }
    const deploys = /deploy/i.test(name) || /environment:\s*['"]?prod/i.test(text);
    if (deploys && /\bpush\b|\brelease\b|\bworkflow_run\b/.test(text)) {
      deploy.push(name);
    }
  }
  return { pullRequest, deploy, skippedBlocks };
}

/** Rules of the default branch, as `GET /repos/{o}/{r}/rules/branches/{b}` returns them. */
function rulesOf(rules) {
  const list = Array.isArray(rules) ? rules : [];
  const checks = list
    .filter((rule) => rule.type === "required_status_checks")
    .flatMap((rule) => rule.parameters?.required_status_checks ?? [])
    .map((check) => check.context);
  const queue = list.find((rule) => rule.type === "merge_queue");
  return { checks, queue };
}

/** Required checks of a classic branch protection (`GET /repos/{o}/{r}/branches/{b}/protection`). */
function protectionChecks(protection) {
  const required = protection?.required_status_checks;
  if (!required) return [];
  return [...(required.contexts ?? []), ...(required.checks ?? []).map((check) => check.context)];
}

export async function detect({ checkout, github, registered = [] }) {
  const repo = await readJson(join(github, "repo.json"), null);
  if (!repo?.full_name) throw new Error(`${github}/repo.json: no full_name`);
  const branches = (await readJson(join(github, "branches.json"), [])).map((branch) => branch.name);
  const pulls = await readJson(join(github, "pulls.json"), []);
  const rules = rulesOf(await readJson(join(github, "rules.json"), []));
  const classic = protectionChecks(await readJson(join(github, "protection.json"), null));
  const checks = [...new Set([...rules.checks, ...classic])];
  const { queue } = rules;
  const files = new Set((await git(checkout, ["ls-files"])).split("\n").filter(Boolean));
  const pkg = (await readJson(join(checkout, "package.json"), null)) ?? {};
  const scripts = pkg.scripts ?? {};
  const pm = packageManager(files);
  const workflows = await workflowRuns(checkout);
  const fields = {};
  const defaultBranch = repo.default_branch;

  fields.fullName = field(repo.full_name, "GitHub app: repo.json full_name");

  const bases = pulls.map((pull) => pull.baseRefName ?? pull.base?.ref).filter(Boolean);
  const toDevelop = bases.filter((base) => base === "develop").length;
  const develop = branches.includes("develop") && toDevelop * 2 > bases.length;
  fields.targetBranch = develop
    ? field(
        "develop",
        `develop exists and ${toDevelop} of the last ${bases.length} merged PRs target it`,
      )
    : field(
        defaultBranch,
        `default branch (${toDevelop} of ${bases.length} recent PRs target develop)`,
      );
  fields.productionBranch = field(defaultBranch, "default branch");
  fields.promotion = develop
    ? field("pull-request", "target branch differs from the production branch")
    : field("none", "pull requests target the production branch");
  const backMerges = develop
    ? pulls.filter(
        (pull) =>
          (pull.headRefName ?? pull.head?.ref) === defaultBranch &&
          (pull.baseRefName ?? pull.base?.ref) === "develop",
      ).length
    : 0;
  fields.backMerge = field(
    backMerges > 0,
    develop ? `${backMerges} recent PRs merged ${defaultBranch} into develop` : "no promotion",
  );

  fields.mode = queue
    ? field("queue", "rules.json: merge_queue rule on the default branch")
    : field("human", "no merge queue rule: a person merges");
  const queueMethod = queue?.parameters?.merge_method?.toLowerCase();
  fields.method =
    queueMethod === "merge" || queueMethod === "squash"
      ? field(queueMethod, "rules.json: merge_queue merge_method")
      : repo.allow_squash_merge !== false
        ? field("squash", "repo.json: squash merge allowed")
        : field("merge", "repo.json: squash merge not allowed");

  fields.source = checks.length
    ? field("ci", `rulesets and branch protection: required checks ${checks.join(", ")}`)
    : field("factory", "no required status check on the default branch");

  const verify = [];
  for (const name of VERIFY_SCRIPTS) {
    if (scripts[name])
      verify.push({ command: `${pm} run ${name}`, from: `package.json scripts.${name}` });
  }
  for (const { command, file } of workflows.pullRequest) {
    const proves = /^(pnpm|npm|yarn|bun|npx|node|make|cargo|go|pytest|uv|poetry)\b/.test(command);
    if (proves && !SETUP_STEP.test(command)) {
      if (!verify.some((entry) => entry.command === command)) {
        verify.push({ command, from: `.github/workflows/${file}` });
      }
    }
  }
  fields.verify = field(
    verify.map((entry) => entry.command).join("\n"),
    verify.length
      ? verify.map((entry) => `${entry.command} ← ${entry.from}`).join("; ")
      : "none found",
  );
  if (workflows.skippedBlocks.length) {
    fields.verify.source += `; multi-line run: blocks not read, re-read them in ${workflows.skippedBlocks.join(
      ", ",
    )}`;
  }
  fields.pathGates = field("", "none proposed: add one per path a reviewer names");

  const withheld = [];
  if ([...files].some((path) => path.startsWith(".github/workflows/")))
    withheld.push(".github/workflows/**");
  const migrationDirs = new Set(
    [...files].map((path) => path.match(/^(.*?(?:migrations|migrate))\//)?.[1]).filter(Boolean),
  );
  for (const dir of migrationDirs) withheld.push(`${dir}/**`);
  fields.withheld = field(withheld.join("\n"), "workflows and migration folders in the checkout");

  const generated = new Set();
  const attributes = (await readText(join(checkout, ".gitattributes"))) ?? "";
  for (const line of attributes.split("\n")) {
    const [pattern, ...flags] = line.trim().split(/\s+/);
    if (
      pattern &&
      flags.some((flag) => flag === "linguist-generated" || flag === "linguist-generated=true")
    ) {
      generated.add(pattern);
    }
  }
  const marked = await git(checkout, [
    "grep",
    "-l",
    "-I",
    ...GENERATED_MARKERS.flatMap((marker) => ["-e", marker]),
    "--",
    ".",
    ":!*.md",
    ":!**/node_modules/**",
  ]);
  for (const path of marked.split("\n").filter(Boolean).slice(0, 200)) {
    const head = ((await readText(join(checkout, path))) ?? "").split("\n").slice(0, 5).join("\n");
    if (GENERATED_MARKERS.some((marker) => head.includes(marker))) generated.add(path);
  }
  fields.generated = field(
    [...generated].join("\n"),
    ".gitattributes linguist-generated, files whose first lines say they are generated",
  );

  const envFiles = [...files].filter((path) => /(^|\/)\.env(\.[\w-]+)?$/.test(path));
  fields.sensitiveData = field(
    envFiles.length ? `Values of the variables named in ${envFiles.join(", ")}` : "",
    envFiles.length ? "tracked env example files" : "none found: ask what must never be quoted",
  );

  fields.environment = field("", "to create: an Environment on the standards-code image (§ 3)");

  const launch = await readJson(join(checkout, ".claude", "launch.json"), null);
  const configurations = launch?.configurations ?? [];
  if (configurations.length) {
    fields.boot = field(
      configurations
        .map(
          (config) =>
            `${[config.runtimeExecutable, ...(config.runtimeArgs ?? [])].join(" ")} → :${
              config.port
            }`,
        )
        .join("\n"),
      ".claude/launch.json",
    );
    fields.apps = field(
      configurations
        .map((config) => `${config.name}, ${config.port}, ${config.url ?? "/"}`)
        .join("\n"),
      ".claude/launch.json",
    );
  } else if (scripts.dev) {
    fields.boot = field(`${pm} run dev`, "package.json scripts.dev");
    fields.apps = field("", "no .claude/launch.json: name each app, port and entry");
  } else {
    fields.boot = field("", "no .claude/launch.json and no dev script");
    fields.apps = field("", "none found");
  }
  const reset = RESET_SCRIPTS.find((name) => scripts[name]);
  fields.reset = reset
    ? field(`${pm} run ${reset}`, `package.json scripts.${reset}`)
    : field("", "no reset or seed script");

  const manifests = [...files].filter(
    (path) => /(^|\/)package\.json$/.test(path) && !path.includes("node_modules"),
  );
  const dependencies = new Set();
  for (const path of manifests) {
    const manifest = (await readJson(join(checkout, path), null)) ?? {};
    for (const key of ["dependencies", "devDependencies", "peerDependencies"]) {
      for (const name of Object.keys(manifest[key] ?? {})) dependencies.add(name);
    }
  }
  const consumes = registered
    .filter((entry) => entry.fullName !== repo.full_name)
    .filter((entry) => (entry.packages ?? []).some((name) => dependencies.has(name)));
  fields.consumes = field(
    consumes.map((entry) => entry.fullName).join("\n"),
    consumes.length
      ? consumes
          .map(
            (entry) =>
              `${entry.fullName}: ${entry.packages
                .filter((name) => dependencies.has(name))
                .join(", ")}`,
          )
          .join("; ")
      : "no dependency on a registered repository's package",
  );
  fields.deploySignal = field(
    workflows.deploy.length
      ? `GitHub workflow ${workflows.deploy.join(", ")} on ${defaultBranch}`
      : "",
    workflows.deploy.length
      ? "deploy workflows in .github/workflows"
      : "none found: no deploy data until set",
  );

  const gate = { requiredChecks: checks, verify: verify.map((entry) => entry.command) };
  return { fields, gate, hasGate: checks.length > 0 || verify.length > 0 };
}

function table({ fields, hasGate }) {
  const rows = Object.entries(fields).map(
    ([name, { value, source }]) =>
      `| ${name} | ${String(value).replaceAll("\n", "<br>") || "–"} | ${source} |`,
  );
  return [
    "| Field | Proposed | Source |",
    "|---|---|---|",
    ...rows,
    "",
    hasGate ? "Gate: found." : "Gate: NONE (no required check, no verify command). Do not save.",
  ].join("\n");
}

function parseArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 2) {
    const flag = argv[index];
    if (!flag.startsWith("--") || argv[index + 1] === undefined)
      throw new Error(`unexpected ${flag}`);
    options[flag.slice(2)] = argv[index + 1];
  }
  if (!options.checkout || !options.github) throw new Error("--checkout and --github are required");
  return options;
}

async function main() {
  let result;
  let options;
  try {
    options = parseArgs(process.argv.slice(2));
    const registered = options.registered ? await readJson(options.registered, []) : [];
    result = await detect({ checkout: options.checkout, github: options.github, registered });
  } catch (error) {
    console.error(
      `${error.message}\nusage: detect.mjs --checkout <dir> --github <dir> [--registered <file>] [--format table]`,
    );
    process.exit(2);
  }
  console.log(options.format === "table" ? table(result) : JSON.stringify(result, null, 2));
  process.exit(result.hasGate ? 0 : 1);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
