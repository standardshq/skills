#!/usr/bin/env node
/**
 * Discovers the facts of a repository at run time.
 *
 *   node discover-repository.mjs --checkout <dir> --github <dir> [--listed <file>]
 *
 * `--checkout` is a clone of the repository. `--github` is a folder of JSON
 * the agent fetched with its GitHub tools: `repo.json`, `branches.json`,
 * `rules.json` (the rulesets that apply to the branch being run: the default
 * branch, or the printed one after an exit 3),
 * `protection.json` (its classic branch protection; absent or a 404 body when
 * there is none) and `pulls.json` (recent merged pull requests). Required
 * checks are the union of rulesets and protection. `--listed` is
 * `[{ "fullName", "packages": ["<package name>"] }]` for the repositories
 * already listed, to find `consumes`.
 *
 * A `## Factory` section of the checkout's `AGENTS.md` overrides discovery,
 * one `key: value` per line: `targetBranch: <branch>`, `skipVerify: <command>`,
 * `withheld: <glob>`. Any other key is ignored.
 *
 * The script reads files and runs git on the checkout; it never calls GitHub.
 * It prints one JSON object of facts, each string newline-joined when it
 * holds a list, plus `gate`: "ci" when required checks exist, else "verify"
 * when `verify` holds a command, else "none". The script never prints "both":
 * a command added through the record's `notes` is what makes it.
 *
 * Exit 0: facts produced. 2: usage or input error. 3: the checkout is not on
 * the target branch; stdout is exactly `{"targetBranch":"<branch>"}`.
 */
import { execFile } from "node:child_process";
import { readFile, readdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);

/** Scripts that prove a change, in the order a gate should run them. */
const VERIFY_SCRIPTS = ["typecheck", "lint", "check", "test", "build"];
/** Scripts that restore seeded data. */
const RESET_SCRIPTS = ["db:reset", "reset", "seed", "db:seed"];
/** Workflow steps that prepare or tear down rather than prove. */
const SETUP_STEP = /\b(install|setup|down|create|resolve|sync|deploy|publish|upload)\b/;
/** Header markers of a file that is never edited by hand. */
const GENERATED_MARKERS = ["@generated", "DO NOT EDIT", "Code generated by", "auto-generated"];
/** Where GitHub looks for code owners. */
const CODEOWNERS_PATHS = [".github/CODEOWNERS", "CODEOWNERS", "docs/CODEOWNERS"];
/** What judges a pull request: changing any of it always reaches a person. */
const JUDGING_PATHS = [
  "AGENTS.md",
  "CLAUDE.md",
  ".cursor/rules/**",
  "CODEOWNERS",
  ".github/CODEOWNERS",
  "docs/CODEOWNERS",
];

async function readJson(path, fallback) {
  try {
    return JSON.parse(await readFile(path, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return fallback;
    throw new Error(`${path}: ${error.message}`);
  }
}

async function readText(path) {
  try {
    return await readFile(path, "utf8");
  } catch {
    return "";
  }
}

/** Runs git on the checkout. A failure is an input error; `git grep` finding nothing is not one. */
async function git(checkout, args, { emptyExit } = {}) {
  try {
    const { stdout } = await run("git", ["-C", checkout, ...args], { maxBuffer: 64 * 1024 * 1024 });
    return stdout.trim();
  } catch (error) {
    if (error.code === emptyExit) return "";
    throw new Error(`git ${args.join(" ")} failed in ${checkout}: ${error.stderr?.trim() || error.message}`);
  }
}

function packageManager(files) {
  if (files.has("pnpm-lock.yaml")) return "pnpm";
  if (files.has("yarn.lock")) return "yarn";
  if (files.has("bun.lockb") || files.has("bun.lock")) return "bun";
  return "npm";
}

/**
 * Single-line `run:` steps of the workflow jobs a pull request triggers.
 * Multi-line `run: |` and `run: >` blocks are skipped.
 */
async function workflowRuns(checkout) {
  const dir = join(checkout, ".github", "workflows");
  let names = [];
  try {
    names = (await readdir(dir)).filter((name) => /\.ya?ml$/.test(name));
  } catch {
    return { pullRequest: [], deploy: [] };
  }
  const pullRequest = [];
  const deploy = [];
  for (const name of names) {
    const text = await readText(join(dir, name));
    const commands = [...text.matchAll(/^\s*(?:-\s*)?run:\s*([^|>\n][^\n]*)$/gm)].map((match) =>
      match[1].trim(),
    );
    if (/\bpull_request\b|\bmerge_group\b/.test(text)) pullRequest.push(...commands);
    const deploys = /deploy/i.test(name) || /environment:\s*['"]?prod/i.test(text);
    if (deploys && /\bpush\b|\brelease\b|\bworkflow_run\b/.test(text)) deploy.push(name);
  }
  return { pullRequest, deploy };
}

/** Rules of the branch being run, as `GET /repos/{o}/{r}/rules/branches/{b}` returns them. */
function rulesOf(rules) {
  const list = Array.isArray(rules) ? rules : [];
  const checks = list
    .filter((rule) => rule.type === "required_status_checks")
    .flatMap((rule) => rule.parameters?.required_status_checks ?? [])
    .map((check) => check.context);
  const queue = list.find((rule) => rule.type === "merge_queue");
  return { checks, queue };
}

/** Required checks of a classic branch protection (`GET /repos/{o}/{r}/branches/{b}/protection`). */
function protectionChecks(protection) {
  const required = protection?.required_status_checks;
  if (!required) return [];
  return [...(required.contexts ?? []), ...(required.checks ?? []).map((check) => check.context)];
}

/** The `key: value` lines under the `## Factory` heading of AGENTS.md, as lists of values per key. */
function factoryInstructions(agents) {
  const instructions = { targetBranch: [], skipVerify: [], withheld: [] };
  let inside = false;
  for (const line of agents.split("\n")) {
    if (/^#{1,6}\s/.test(line)) {
      inside = /^##\s+Factory\s*$/.test(line);
      continue;
    }
    const match = inside && line.match(/^\s*(\w+):\s*(.+?)\s*$/);
    if (match && match[1] in instructions) instructions[match[1]].push(match[2]);
  }
  return instructions;
}

/**
 * One CODEOWNERS pattern as the globs of the paths it owns. A pattern is
 * anchored when it starts with a slash or has one inside; a name with no glob
 * character may be a folder, so it also owns what is inside it.
 */
function ownedGlobs(pattern) {
  const body = pattern.replace(/^\//, "");
  const anchored = pattern.startsWith("/") || body.replace(/\/$/, "").includes("/");
  if (body.endsWith("/")) return [`${anchored ? "" : "**/"}${body}**`];
  return /[*?[]/.test(body) ? [body] : [body, `${body}/**`];
}

/** The globs of every path a person owns; the catch-all `*` owns nothing in particular. */
function ownedPaths(codeowners) {
  return codeowners
    .split("\n")
    .map((line) => line.trim().split(/\s+/)[0])
    .filter((pattern) => pattern && !pattern.startsWith("#") && pattern !== "*")
    .flatMap(ownedGlobs);
}

async function readCodeowners(checkout) {
  for (const path of CODEOWNERS_PATHS) {
    const text = await readText(join(checkout, path));
    if (text) return text;
  }
  return "";
}

function branchFacts({ pulls, branches, defaultBranch, head, override }) {
  const bases = pulls.map((pull) => pull.baseRefName ?? pull.base?.ref).filter(Boolean);
  const toDevelop = bases.filter((base) => base === "develop").length;
  const develop = branches.includes("develop") && toDevelop * 2 > bases.length;
  const derived = develop ? "develop" : defaultBranch;
  // The checked-out branch may name the target only from where the work starts.
  const honoured =
    override && branches.includes(override) && [override, defaultBranch].includes(head);
  const targetBranch = honoured ? override : derived;
  const promotes = targetBranch !== defaultBranch;
  const backMerge =
    promotes &&
    pulls.some(
      (pull) =>
        (pull.headRefName ?? pull.head?.ref) === defaultBranch &&
        (pull.baseRefName ?? pull.base?.ref) === targetBranch,
    );
  return {
    targetBranch,
    productionBranch: defaultBranch,
    promotion: promotes ? "pull-request" : "none",
    backMerge,
  };
}

function verifyCommands({ scripts, pm, workflowCommands, skipped }) {
  const commands = VERIFY_SCRIPTS.filter((name) => scripts[name]).map((name) => `${pm} run ${name}`);
  for (const command of workflowCommands) {
    const proves = /^(pnpm|npm|yarn|bun|npx|node|make|cargo|go|pytest|uv|poetry)\b/.test(command);
    if (proves && !SETUP_STEP.test(command) && !commands.includes(command)) commands.push(command);
  }
  return commands.filter((command) => !skipped.includes(command));
}

async function withheldGlobs({ checkout, files, extra }) {
  const migrationDirs = new Set(
    [...files].map((path) => path.match(/^(.*?(?:migrations|migrate))\//)?.[1]).filter(Boolean),
  );
  return [
    ...new Set([
      ".github/workflows/**",
      ...JUDGING_PATHS,
      ...[...migrationDirs].map((dir) => `${dir}/**`),
      ...ownedPaths(await readCodeowners(checkout)),
      ...extra,
    ]),
  ];
}

async function generatedFiles(checkout) {
  const generated = new Set();
  for (const line of (await readText(join(checkout, ".gitattributes"))).split("\n")) {
    const [pattern, ...flags] = line.trim().split(/\s+/);
    if (pattern && flags.some((flag) => /^linguist-generated(=true)?$/.test(flag))) {
      generated.add(pattern);
    }
  }
  const marked = await git(
    checkout,
    [
      "grep",
      "-l",
      "-I",
      ...GENERATED_MARKERS.flatMap((marker) => ["-e", marker]),
      "--",
      ".",
      ":!*.md",
      ":!**/node_modules/**",
    ],
    { emptyExit: 1 },
  );
  for (const path of marked.split("\n").filter(Boolean).slice(0, 200)) {
    const head = (await readText(join(checkout, path))).split("\n").slice(0, 5).join("\n");
    if (GENERATED_MARKERS.some((marker) => head.includes(marker))) generated.add(path);
  }
  return [...generated];
}

async function bootFacts({ checkout, scripts, pm }) {
  const launch = await readJson(join(checkout, ".claude", "launch.json"), null);
  const configurations = launch?.configurations ?? [];
  if (configurations.length) {
    return {
      boot: configurations
        .map(
          (config) =>
            `${[config.runtimeExecutable, ...(config.runtimeArgs ?? [])].join(" ")} → :${config.port}`,
        )
        .join("\n"),
      apps: configurations
        .map((config) => `${config.name}, ${config.port}, ${config.url ?? "/"}`)
        .join("\n"),
    };
  }
  return { boot: scripts.dev ? `${pm} run dev` : "", apps: "" };
}

async function consumedRepositories({ checkout, files, listed, fullName }) {
  const manifests = [...files].filter(
    (path) => /(^|\/)package\.json$/.test(path) && !path.includes("node_modules"),
  );
  const dependencies = new Set();
  for (const path of manifests) {
    const manifest = (await readJson(join(checkout, path), null)) ?? {};
    for (const key of ["dependencies", "devDependencies", "peerDependencies"]) {
      for (const name of Object.keys(manifest[key] ?? {})) dependencies.add(name);
    }
  }
  return listed
    .filter((entry) => entry.fullName !== fullName)
    .filter((entry) => (entry.packages ?? []).some((name) => dependencies.has(name)))
    .map((entry) => entry.fullName);
}

function gateOf({ checks, verify }) {
  if (checks.length) return "ci";
  return verify.length ? "verify" : "none";
}

export async function discover({ checkout, github, listed = [] }) {
  const repo = await readJson(join(github, "repo.json"), null);
  if (!repo?.full_name) throw new Error(`${github}/repo.json: no full_name`);
  if (!repo.default_branch) throw new Error(`${github}/repo.json: no default_branch`);
  const branches = (await readJson(join(github, "branches.json"), [])).map((branch) => branch.name);
  const pulls = await readJson(join(github, "pulls.json"), []);
  const rules = rulesOf(await readJson(join(github, "rules.json"), []));
  const classic = protectionChecks(await readJson(join(github, "protection.json"), null));
  const checks = [...new Set([...rules.checks, ...classic])];
  const { queue } = rules;
  await git(checkout, ["rev-parse", "--git-dir"]);
  const head = await git(checkout, ["rev-parse", "--abbrev-ref", "HEAD"]);
  const files = new Set((await git(checkout, ["ls-files"])).split("\n").filter(Boolean));
  const scripts = ((await readJson(join(checkout, "package.json"), null)) ?? {}).scripts ?? {};
  const pm = packageManager(files);
  const workflows = await workflowRuns(checkout);
  const instructions = factoryInstructions(await readText(join(checkout, "AGENTS.md")));

  const queueMethod = queue?.parameters?.merge_method?.toLowerCase();
  const method =
    queueMethod === "merge" || queueMethod === "squash"
      ? queueMethod
      : repo.allow_squash_merge !== false
        ? "squash"
        : "merge";
  const verify = verifyCommands({
    scripts,
    pm,
    workflowCommands: workflows.pullRequest,
    skipped: instructions.skipVerify,
  });
  const resetScript = RESET_SCRIPTS.find((name) => scripts[name]);
  const envFiles = [...files].filter((path) => /(^|\/)\.env(\.[\w-]+)?$/.test(path));

  const facts = {
    fullName: repo.full_name,
    ...branchFacts({
      pulls,
      branches,
      defaultBranch: repo.default_branch,
      head,
      override: instructions.targetBranch.at(-1),
    }),
    mode: queue ? "queue" : "human",
    method,
    source: checks.length ? "ci" : "factory",
    verify: verify.join("\n"),
    pathGates: "",
    withheld: (await withheldGlobs({ checkout, files, extra: instructions.withheld })).join("\n"),
    generated: (await generatedFiles(checkout)).join("\n"),
    sensitiveData: envFiles.length ? `Values of the variables named in ${envFiles.join(", ")}` : "",
    ...(await bootFacts({ checkout, scripts, pm })),
    reset: resetScript ? `${pm} run ${resetScript}` : "",
    consumes: (await consumedRepositories({ checkout, files, listed, fullName: repo.full_name })).join("\n"),
    deployWorkflows: workflows.deploy.join("\n"),
    gate: gateOf({ checks, verify }),
  };
  return { facts, onTarget: head === facts.targetBranch };
}

function parseArgs(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 2) {
    const flag = argv[index];
    if (!["--checkout", "--github", "--listed"].includes(flag) || argv[index + 1] === undefined)
      throw new Error(`unexpected ${flag}`);
    options[flag.slice(2)] = argv[index + 1];
  }
  if (!options.checkout || !options.github) throw new Error("--checkout and --github are required");
  return options;
}

async function main() {
  let result;
  try {
    const options = parseArgs(process.argv.slice(2));
    const listed = options.listed ? await readJson(options.listed, []) : [];
    result = await discover({ checkout: options.checkout, github: options.github, listed });
  } catch (error) {
    console.error(
      `${error.message}\nusage: discover-repository.mjs --checkout <dir> --github <dir> [--listed <file>]`,
    );
    process.exit(2);
  }
  if (!result.onTarget) {
    process.stdout.write(JSON.stringify({ targetBranch: result.facts.targetBranch }));
    process.exit(3);
  }
  console.log(JSON.stringify(result.facts, null, 2));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
